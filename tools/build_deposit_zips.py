#!/usr/bin/env python3
"""Build the upload-ready Zenodo deposit for the JOptim analysis.

The deposit contains the experiment and analysis data (cleaned), the stimulus
material, and the analysis environment; the code itself lives in the two
repositories cited by the article (analysis: univiemops/joptim-analysis,
experiment: univiemops/joptim-exp) and is not part of the deposit.

The cleaned deposit replaces all Prolific participant identifiers: the
`pid`, `Participant id`, `Submission id`, and `participant` columns of all
CSV files and data frames are removed (the internal experiment session ids
`xid` and the internal row ids `id` are retained, see zenodo_record_draft.md).
Free-text cells and text files are screened; email addresses, Prolific-id-like
strings, server URLs, API paths, local file paths, and identifying strings are
redacted. Raw data files (`.pkl`) are loaded, the identifier columns are
dropped from all contained data frames, and the cleaned objects are re-pickled;
the resulting files require the pandas version of the repository environment
(staged alongside as `environment.yml`).

Running this script rebuilds the deposit zips from the current state of
DATA_DIR and writes them to DATA_DIR/zenodo:

  data.zip          experiment and analysis data (both studies): raw session
                    tables, preprocessed per-trial CSVs, the MSSP problem
                    pools with their enumerated optimal solutions and
                    complexity metrics (benchmark instances), per-study trial
                    definitions, de-identified Prolific demographic tables,
                    and free-text evaluation-strategy responses
  stimuli.zip       stimulus material (generated problem instances and
                    presentation files)
  stimuli_pairs.zip solution-pair materials for the evaluation trials

plus `environment.yml` copied from this repository and a copy of
DATA_DIR/zenodo_record_draft.md (record metadata) if present.

Not part of the deposit: code (see the repositories), publication
figures/tables (pub/, regenerated by the analysis code), server/analysis
logs, archive copies, the former OSF export, and the intermediate
stimuli inspection directories.

A verification pass runs after the build: every zip member is scanned for
identifier patterns and stray identifier columns; the script exits non-zero
if any hit remains.

Usage:
  python tools/build_deposit_zips.py [data] [stimuli] [stimuli_pairs] [--skip-verify]
"""
from __future__ import annotations

import io
import pickle
import re
import shutil
import sys
import zipfile
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))
from create_osf_data import load_data_dir  # noqa: E402

DATA_ROOT = Path(load_data_dir())
OUT_DIR = DATA_ROOT / "zenodo"

ZIP_DIRS = ["data", "stimuli", "stimuli_pairs"]
SKIP_SUFFIXES = {".tex", ".svg", ".html", ".log", ".md", ".pyc"}
EXCLUDED_PARTS = {"archive", "OSF", "zenodo", "__pycache__", ".ipynb_checkpoints"}

DROP_COLUMNS = {"pid", "Participant id", "Submission id", "participant"}
PICKLE_DROP_COLUMNS = {"pid", "participant", "Participant id", "Submission id"}

TEXT_CLEAN_PATTERNS = [
    (re.compile(r"https?://psycyb-portia\.psy\.univie\.ac\.at(?::\d+)?"), "[REDACTED_URL]"),
    (re.compile(r"psycyb-portia\.psy\.univie\.ac\.at(?::\d+)?"), "[REDACTED_HOST]"),
    (re.compile(r"/joptim-api/[^\s\"'<>]+"), "/joptim-api/[REDACTED]"),
    (re.compile(r"/home/user(?:/[^\s\"'<>]*)?"), "[REDACTED_PATH]"),
    (re.compile(r"Dropbox/data_export/joptim-analysis(?:/[^\s\"'<>]*)?"), "[REDACTED_PATH]"),
    (re.compile(r"\b(?:University of Vienna|Universit(?:y|a)t Wien|Univie)\b", re.IGNORECASE), "[REDACTED_AFFILIATION]"),
    (re.compile(r"\bFilip\b"), "[REDACTED_NAME]"),
    (re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}"), "[REDACTED_EMAIL]"),
    (re.compile(r"\b[0-9a-f]{24}\b"), "[REDACTED_PID]"),
    (re.compile(r"lg24xOKPvU8AxOnC59Lpi22lLBSQiSid|isHDBPyg8MDVc8rCZckSaUWWFTvScPyf|yQYvzJClO1gttwXH3mUnOYKZbZYr2j4R"), "[REDACTED_PID]"),
]

BINARY_SUFFIXES = {".rds", ".pdf", ".zip", ".png", ".jpg", ".jpeg", ".webm", ".gif", ".svg"}

CHECK_PATTERNS = [
    ("prolific-id-24hex", re.compile(r"\b[0-9a-f]{24}\b")),
    ("known-session-pid", re.compile(r"lg24xOKPvU8AxOnC59Lpi22lLBSQiSid|isHDBPyg8MDVc8rCZckSaUWWFTvScPyf|yQYvzJClO1gttwXH3mUnOYKZbZYr2j4R")),
    ("email", re.compile(r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}")),
    ("server-host", re.compile(r"psycyb-portia[^\s]*")),
    ("univie-path", re.compile(r"univie|University of Vienna", re.IGNORECASE)),
]
CHECK_PATTERNS_BINARY = [
    (label, pattern) for label, pattern in CHECK_PATTERNS
    if label not in ("email", "server-host", "univie-path")
]


def iter_files(source_dir: Path):
    for p in sorted(source_dir.rglob("*")):
        if p.is_dir():
            continue
        rel = p.relative_to(source_dir)
        if any(part in EXCLUDED_PARTS for part in Path(source_dir.name, *rel.parts).parts):
            continue
        if p.name.startswith(".") or any(part.startswith(".") for part in rel.parts):
            continue
        if p.suffix in SKIP_SUFFIXES:
            continue
        yield p, rel


def clean_text(text: str) -> str:
    for pattern, replacement in TEXT_CLEAN_PATTERNS:
        text = pattern.sub(replacement, text)
    return text


def csv_dropped(columns: list[str]) -> list[int]:
    return [i for i, col in enumerate(columns) if str(col) in DROP_COLUMNS]


def rebuild_from_csv_rows(
    header: list[str], rows: list[list[str]]
) -> list[list[str]]:
    dropped = csv_dropped(header)
    keep = [i for i in range(len(header)) if i not in dropped]
    out = [[clean_text(row[i]) if i < len(row) else "" for i in keep] for row in rows]
    return [header[i] for i in keep], out


def clean_bytes_for_csv(src: Path) -> str:
    import csv

    with src.open("r", encoding="utf-8-sig", newline="") as f:
        reader = list(csv.reader(f))
    if not reader:
        return ""
    header, rows = reader[0], reader[1:]
    header_out, rows_out = rebuild_from_csv_rows(header, [
        (row + [""] * (len(header) - len(row))) if len(row) < len(header) else row for row in rows
    ])
    import io as _io
    buf = _io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerow(header_out)
    writer.writerows(rows_out)
    return buf.getvalue()


def clean_dataframe(obj):
    if isinstance(obj, dict):
        return {k: clean_dataframe(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [clean_dataframe(v) for v in obj]
    if isinstance(obj, pd.DataFrame):
        cols = [c for c in obj.columns if str(c) in PICKLE_DROP_COLUMNS]
        return obj.drop(columns=cols) if cols else obj
    return obj


def clean_bytes_for_pickle(src: Path) -> bytes:
    with src.open("rb") as f:
        obj = pickle.load(f)
    return pickle.dumps(clean_dataframe(obj))


def build_dir_zip(source_dir: Path, dest: Path) -> None:
    if not source_dir.is_dir():
        raise SystemExit(f"missing source directory: {source_dir}")
    n = 0
    with zipfile.ZipFile(dest, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
        for p, rel in iter_files(source_dir):
            arcname = str(Path(source_dir.name) / rel)
            if p.suffix == ".csv":
                zf.writestr(arcname, clean_bytes_for_csv(p))
            elif p.suffix == ".pkl":
                zf.writestr(arcname, clean_bytes_for_pickle(p))
            elif p.suffix in {".json", ".txt"}:
                zf.writestr(arcname, clean_text(p.read_text(encoding="utf-8", errors="ignore")))
            else:
                zf.write(p, arcname)
            n += 1
    print(f"  {dest.name}: {n} files, {dest.stat().st_size / 1e6:.1f} MB")


def verify_dest() -> int:
    findings = 0
    print("verification:")
    for dest in sorted(OUT_DIR.glob("*.zip")):
        with zipfile.ZipFile(dest) as zf:
            for info in zf.infolist():
                if info.is_dir():
                    continue
                name = info.filename
                base = Path(name).name
                if base in DROP_COLUMNS or Path(name).stem in DROP_COLUMNS:
                    print(f"  FAIL {dest.name}/{name}: identifier column name")
                    findings += 1
                    continue
                if name.endswith(".pkl"):
                    with zf.open(name) as f:
                        obj = pickle.load(f)
                    stack = [obj]
                    while stack:
                        o = stack.pop()
                        if isinstance(o, dict):
                            stack.extend(o.values())
                        elif isinstance(o, list):
                            stack.extend(o)
                        elif isinstance(o, pd.DataFrame):
                            bad = [c for c in o.columns if str(c) in PICKLE_DROP_COLUMNS]
                            if bad:
                                print(f"  FAIL {dest.name}/{name}: identifier column(s) {bad}")
                                findings += 1
                    continue
                if Path(name).suffix in BINARY_SUFFIXES:
                    data = zf.read(name)
                    for label, pattern in CHECK_PATTERNS_BINARY:
                        m = pattern.search(data.decode("utf-8", errors="ignore"))
                        if m:
                            context = (
                                data[max(0, m.start() - 40): m.end() + 20]
                                .decode("utf-8", errors="ignore")
                                .replace("\n", " ")
                            )
                            print(f"  FAIL {dest.name}/{name}: {label}: ...{context}...")
                            findings += 1
                    continue
                text = zf.read(name).decode("utf-8", errors="ignore")
                for label, pattern in CHECK_PATTERNS:
                    m = pattern.search(text)
                    if m:
                        context = text[max(0, m.start() - 40): m.end() + 20].replace("\n", " ")
                        print(f"  FAIL {dest.name}/{name}: {label}: ...{context}...")
                        findings += 1
    if findings == 0:
        print("  all zip members clean (no identifier patterns, no identifier columns)")
    return 1 if findings else 0


def main() -> int:
    parts = [a for a in sys.argv[1:] if not a.startswith("--")]
    skip_verify = "--skip-verify" in sys.argv
    parts = parts or list(ZIP_DIRS)
    unknown = [p for p in parts if p not in ZIP_DIRS]
    if unknown:
        raise SystemExit(f"unknown part(s): {unknown}; expected subset of {ZIP_DIRS}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    print(f"deposit output: {OUT_DIR}")
    for name in parts:
        print(f"{name}.zip:")
        build_dir_zip(DATA_ROOT / name, OUT_DIR / f"{name}.zip")

    for staged in [
        REPO / "environment.yml",
        DATA_ROOT / "zenodo_record_draft.md",
    ]:
        if staged.exists():
            shutil.copy2(staged, OUT_DIR / staged.name)
            print(f"  staged {staged.name}")

    if skip_verify:
        print("verification skipped")
        return 0
    return verify_dest()


if __name__ == "__main__":
    raise SystemExit(main())
